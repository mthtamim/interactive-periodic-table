#!/usr/bin/env python3
"""Apply the permanent debug signing key to Capacitor's generated
android/app/build.gradle (regenerated by `npx cap add android` on
every CI run, so the signing config cannot live in the repo file).

Idempotent: does nothing if signingConfigs is already present.
Usage: python3 scripts/apply-debug-signing.py android/app/build.gradle
"""
import sys

SIGNING_CONFIGS = """    signingConfigs {
        // 2026-11-06: ONE fixed debug key for every build. Before this,
        // assembleDebug signed with a fresh keystore generated on
        // each CI runner, so every build had a different signature
        // and Android refused to install it over the previous one
        // ("App not installed"). The keystore is decoded from
        // debug.keystore.b64 (repo root) by the workflow before this
        // script runs. DEBUG-only key, never for releases.
        debug {
            storeFile file("debug.keystore")
            storePassword "android"
            keyAlias "androiddebugkey"
            keyPassword "android"
            storeType "PKCS12"
        }
    }

"""

DEBUG_BUILD_TYPE = """        debug {
            signingConfig signingConfigs.debug
        }
"""


def main() -> int:
    path = sys.argv[1]
    text = open(path).read()
    if "signingConfigs" in text:
        print("already patched, nothing to do")
        return 0
    anchor = "    buildTypes {\n"
    assert anchor in text, "buildTypes block not found"
    text = text.replace(anchor, SIGNING_CONFIGS + anchor, 1)
    text = text.replace(anchor, anchor + DEBUG_BUILD_TYPE, 1)
    open(path, "w").write(text)
    print("patched", path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
